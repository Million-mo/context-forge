#!/usr/bin/env node
/**
 * bin/build-plugins.mjs
 *
 * Generates opencode plugin files (.mjs) from TypeScript source (.ts).
 *
 * Flow:
 *   1. TypeScript compile src/*.ts → dist/*.js  (stripped of types)
 *   2. Copy dist/*.js → .opencode/plugins/*.mjs  (add header, strip types in a second pass)
 *
 * Using Node.js native ESM only — no tsx needed.
 *
 * Usage:
 *   node bin/build-plugins.mjs
 *   npm run build:plugins
 */

import { spawnSync } from "node:child_process"
import { existsSync, mkdirSync, copyFileSync, readFileSync, writeFileSync, readdirSync, rmSync } from "node:fs"
import { resolve, dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import { homedir } from "node:os"

const __filename = fileURLToPath(import.meta.url)
const ROOT = resolve(dirname(__filename), "..")

// ── Config ────────────────────────────────────────────────────────────────────

const TSC = resolve(ROOT, "node_modules", ".bin", "tsc")
const TSCCONFIG = resolve(ROOT, "tsconfig.json")
const DIST_DIR = resolve(ROOT, "dist")

const OPENCODE_CONFIG_DIR = process.env.OPENCODE_CONFIG_DIR ||
  (process.env.XDG_CONFIG_HOME && resolve(process.env.XDG_CONFIG_HOME, "opencode")) ||
  (process.platform === "win32"
    ? resolve(process.env.APPDATA || resolve(homedir(), "AppData", "Roaming"), "opencode")
    : resolve(homedir(), ".config", "opencode"))
const PLUGINS_OUT = resolve(OPENCODE_CONFIG_DIR, "plugins")

const PLUGINS = [
  {
    name: "caveman",
    srcTs: join(ROOT, "src", "caveman.ts"),
    distJs: join(DIST_DIR, "caveman.js"),
    outMjs: join(PLUGINS_OUT, "caveman.mjs"),
    srcName: "ctx_plugin/src/caveman.ts",
    // Caveman only imports node:* modules, no project deps needed
    deps: [],
  },
  {
    name: "routing",
    srcTs: join(ROOT, "src", "routing-plugin.ts"),
    distJs: join(DIST_DIR, "routing-plugin.js"),
    outMjs: join(PLUGINS_OUT, "routing.mjs"),
    srcName: "ctx_plugin/src/routing-plugin.ts",
    // Routing imports from hooks/ and security.ts — copy these alongside
    deps: [
      { src: join(DIST_DIR, "security.js"),       dst: join(PLUGINS_OUT, "security.js") },
      { src: join(DIST_DIR, "hooks"),             dst: join(PLUGINS_OUT, "hooks") },
    ],
  },
  {
    name: "transform",
    srcTs: join(ROOT, "src", "transform.ts"),
    distJs: join(DIST_DIR, "transform.js"),
    outMjs: join(PLUGINS_OUT, "transform.mjs"),
    srcName: "ctx_plugin/src/transform.ts",
    // Transform only imports node:builtins, no project deps needed
    deps: [],
  },
]

const PLUGIN_HEADER = (name, src) =>
  `/**
 * ${name} plugin — opencode plugin
 *
 * Source of truth: ${src}
 * Do not edit manually — generated by bin/build-plugins.mjs.
 */\n\n`

// ── TypeScript stripper ───────────────────────────────────────────────────────
// Strips TypeScript annotations from compiled JS so it runs as valid ESM .mjs.
// Operates on already-compiled output (no interface/enum declarations remaining).

function stripTypes(code) {
  let result = code

  // Preserve: import * as ns from "..."
  // (must happen before general stripping)
  const nsImports = []
  result = result.replace(/import\s+\*\s+as\s+(\w+)\s+from\s+["']([^"']+)["'];?/g, (_, ns, pkg) => {
    nsImports.push({ ns, pkg })
    return `__NS_IMPORT_${nsImports.length - 1}__`
  })

  // Remove 'as Type' casts
  result = result.replace(/\bas\s+\w+(\[\])?(\s*\|\s*\w+(\[\])?)*/g, "")

  // Remove const assertions
  result = result.replace(/\bas\s+const\b/g, "")

  // NOTE: Non-null assertions (`x!.foo`, `x!`) are already stripped by tsc.
  // Do NOT run a regex here — it will corrupt `!==` / `!=` operators.
  // If a non-null assertion survives tsc (shouldn't happen), it's harmless in JS.

  // Remove generic parameters from function calls
  result = result.replace(/<(?!\s*)(?![A-Z][a-z])[^>{}]+>(?=\s*[\(])/g, "")

  // Remove unknown/any types
  result = result.replace(/<\s*unknown\s*>/g, "")
  result = result.replace(/<\s*any\s*>/g, "")

  // Remove type parameter defaults
  result = result.replace(/<\w+\s*=\s*\w+(\[\])?(\s*\|\s*\w+(\[\])?)*>/g, "<_>")

  // Restore namespace imports
  for (let i = 0; i < nsImports.length; i++) {
    result = result.replace(`__NS_IMPORT_${i}__`, `import * as ${nsImports[i].ns} from "${nsImports[i].pkg}";`)
  }

  // Clean up empty lines
  result = result.replace(/\n{3,}/g, "\n\n")

  return result
}

// ── Step 1: Compile TypeScript ─────────────────────────────────────────────────

console.log("Compiling TypeScript...")
const tscResult = spawnSync(TSC, ["--project", TSCCONFIG], { stdio: "inherit" })
if (tscResult.status !== 0) {
  console.error("tsc failed — fix type errors first")
  process.exit(1)
}
console.log("  ✓ TypeScript compiled\n")

// ── Step 2: Copy & transform each plugin ──────────────────────────────────────

mkdirSync(PLUGINS_OUT, { recursive: true })

for (const plugin of PLUGINS) {
  if (!existsSync(plugin.distJs)) {
    console.error(`  ✗ dist file missing: ${plugin.distJs}`)
    process.exit(1)
  }

  let code = readFileSync(plugin.distJs, "utf8")

  // Replace the source-file JSDoc header with a "generated from" header
  code = code.replace(
    /^\/\*\*\s*\n([\s\S]*?)\*\/\n/,
    PLUGIN_HEADER(plugin.name, plugin.srcName)
  )

  code = stripTypes(code)

  writeFileSync(plugin.outMjs, code, "utf8")
  console.log(`  ✓ ${plugin.name}.mjs → ${resolve(PLUGINS_OUT, plugin.name + ".mjs").replace(resolve(ROOT, "..") + "/", "")}`)
}

// ── Step 3: Copy dependency modules for standalone plugin resolution ──────────

for (const plugin of PLUGINS) {
  if (!plugin.deps || plugin.deps.length === 0) continue

  for (const dep of plugin.deps) {
    if (!existsSync(dep.src)) {
      console.error(`  ⚠ dep not found: ${dep.src}`)
      continue
    }

    const dstParent = dirname(dep.dst)
    if (!existsSync(dstParent)) {
      mkdirSync(dstParent, { recursive: true })
    }

    if (dep.src.endsWith(".js")) {
      // Single file copy (skip if already exists — tsc output is up to date)
      if (!existsSync(dep.dst)) {
        copyFileSync(dep.src, dep.dst)
        const shortName = dep.dst.replace(resolve(ROOT, "..") + "/", "")
        console.log(`  ✓ dep ${shortName}`)
      }
    } else {
      // Directory copy — copy all .js files
      if (!existsSync(dep.dst)) {
        mkdirSync(dep.dst, { recursive: true })
      }
      const entries = readdirSync(dep.src)
      for (const entry of entries) {
        const srcPath = join(dep.src, entry)
        const dstPath = join(dep.dst, entry)
        if (entry.endsWith(".js") && !existsSync(dstPath)) {
          copyFileSync(srcPath, dstPath)
          const shortName = dstPath.replace(resolve(ROOT, "..") + "/", "")
          console.log(`  ✓ dep ${shortName}`)
        }
      }
    }
  }
}

console.log("\nDone. Restart opencode to use updated plugins.")
